  return `${summaryText}. ${text.steps} ${steps}. ${text.sleep} ${sleepChange}. ${text.heartRate} ${avgHeartRate} bpm. ${text.calories} ${caloriesBurned}. ${text.healthScore} ${healthScore}. ${text.wellness} ${overallWellness}. ${sleepAdvice}`
