function deriveSleepChange(avgSleep) {
  const parsed = Number(avgSleep)
  if (!Number.isFinite(parsed) || parsed <= 0) return '+0hrs'

  const baseline = 8
  const delta = Number((parsed - baseline).toFixed(1))
  if (Math.abs(delta) < 0.1) return '+0hrs'

  return `${delta > 0 ? '+' : ''}${delta}hrs`
}

function formatUpdatedTime(iso) {
  if (!iso) return 'UPDATED JUST NOW'
  const diff = Date.now() - new Date(iso).getTime()
  const minutes = Math.floor(diff / 60000)

  if (minutes < 1) return 'UPDATED JUST NOW'
  if (minutes < 60) return `UPDATED ${minutes}M AGO`

  const hours = Math.floor(minutes / 60)
  if (hours < 24) return `UPDATED ${hours}H AGO`

  return `UPDATED ${Math.floor(hours / 24)}D AGO`
}

